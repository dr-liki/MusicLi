package com.lostf1sh.pixelplayeross.data.network.lyrics.providers

import com.lostf1sh.pixelplayeross.data.video.YouTubeStreamExtractor
import okhttp3.OkHttpClient
import java.util.Locale
import javax.inject.Inject
import javax.inject.Singleton
import kotlin.math.abs

@Singleton
class YouTubeLyricsProvider @Inject constructor(
    private val youTubeStreamExtractor: YouTubeStreamExtractor,
    private val okHttpClient: OkHttpClient,
) : LyricsProvider {

    override val id: LyricsProviderId = LyricsProviderId.YOUTUBE

    override suspend fun search(
        title: String,
        artist: String?,
        album: String?,
        durationMs: Long?,
    ): List<LyricsProviderCandidate> {
        val cleanTitle = title.trim()
        val cleanArtist = artist?.trim().orEmpty()
        if (cleanTitle.isBlank()) return emptyList()

        val query = listOfNotNull(
            cleanTitle.takeIf { it.isNotBlank() },
            cleanArtist.takeIf { it.isNotBlank() },
            "lyrics"
        ).joinToString(" ")

        val videos = youTubeStreamExtractor.searchVideos(query, limit = 4)
        if (videos.isEmpty()) return emptyList()

        val targetSec = durationMs?.takeIf { it > 0L }?.div(1000.0)
        val sortedVideos = if (targetSec != null) {
            videos.sortedBy { video ->
                val vDur = video.durationSeconds?.toDouble() ?: return@sortedBy Double.MAX_VALUE
                abs(vDur - targetSec)
            }
        } else {
            videos
        }

        val candidates = mutableListOf<LyricsProviderCandidate>()
        for (video in sortedVideos.take(2)) {
            val tracks = youTubeStreamExtractor.fetchSubtitleTracks(video.videoId)
            val chosen = selectBestSubtitleTrack(tracks) ?: continue
            val payload = ProviderHttpClient.getText(okHttpClient, chosen.url) ?: continue
            val lrc = parseCaptionsToLrc(payload) ?: continue

            candidates += LyricsProviderCandidate(
                externalId = video.videoId,
                providerId = id,
                title = video.title.ifBlank { cleanTitle },
                artistName = video.channel.ifBlank { cleanArtist },
                albumName = "",
                durationSec = video.durationSeconds?.toDouble(),
                rawLyrics = lrc,
                hasSyncedContent = true,
                hasWordSync = false,
                attributionUrl = "https://www.youtube.com/watch?v=${video.videoId}",
            )
        }
        return candidates
    }

    private fun selectBestSubtitleTrack(
        tracks: List<YouTubeStreamExtractor.SubtitleTrackInfo>
    ): YouTubeStreamExtractor.SubtitleTrackInfo? {
        if (tracks.isEmpty()) return null
        val manual = tracks.filterNot { it.isAutoGenerated }
        val pool = manual.ifEmpty { tracks }
        return pool.firstOrNull { it.languageTag.startsWith("en", ignoreCase = true) }
            ?: pool.firstOrNull()
    }

    companion object {
        private val VTT_CUE_TIME_REGEX = Regex(
            """((?:\d{1,2}:)?\d{2}:\d{2}[.,]\d{3})\s*-->\s*((?:\d{1,2}:)?\d{2}:\d{2}[.,]\d{3})"""
        )
        private val XML_TEXT_REGEX = Regex(
            """<text\s+start="([\d.]+)"(?:\s+dur="([\d.]+)")?[^>]*>(.*?)</text>""",
            setOf(RegexOption.DOT_MATCHES_ALL, RegexOption.IGNORE_CASE)
        )
        private val SRV3_P_REGEX = Regex(
            """<p\s+t="(\d+)"(?:\s+d="(\d+)")?[^>]*>(.*?)</p>""",
            setOf(RegexOption.DOT_MATCHES_ALL, RegexOption.IGNORE_CASE)
        )
        private val HTML_TAG_REGEX = Regex("""<[^>]+>""")
        private val NOISE_CUE_REGEX = Regex(
            """^\s*[\[(](music|instrumental|applause|laughter|cheering|intro|outro)[\])]\s*$""",
            RegexOption.IGNORE_CASE
        )

        internal fun parseCaptionsToLrc(rawPayload: String): String? {
            val trimmed = rawPayload.trim()
            if (trimmed.isBlank()) return null

            if (trimmed.startsWith("<tt", ignoreCase = true) || trimmed.contains("<tt ", ignoreCase = true)) {
                return trimmed
            }

            val cues: List<Pair<Long, String>> = when {
                XML_TEXT_REGEX.containsMatchIn(trimmed) -> {
                    XML_TEXT_REGEX.findAll(trimmed).mapNotNull { match ->
                        val startSec = match.groupValues[1].toDoubleOrNull() ?: return@mapNotNull null
                        val text = cleanCueText(match.groupValues[3]) ?: return@mapNotNull null
                        (startSec * 1000.0).toLong() to text
                    }.toList()
                }
                SRV3_P_REGEX.containsMatchIn(trimmed) -> {
                    SRV3_P_REGEX.findAll(trimmed).mapNotNull { match ->
                        val startMs = match.groupValues[1].toLongOrNull() ?: return@mapNotNull null
                        val text = cleanCueText(match.groupValues[3]) ?: return@mapNotNull null
                        startMs to text
                    }.toList()
                }
                else -> parseVttOrSrtCues(trimmed)
            }

            if (cues.isEmpty()) return null

            val deduplicated = mutableListOf<Pair<Long, String>>()
            for ((ms, text) in cues.sortedBy { it.first }) {
                if (deduplicated.lastOrNull()?.second.equals(text, ignoreCase = true)) continue
                deduplicated += ms to text
            }
            if (deduplicated.size < 3) return null

            return deduplicated.joinToString("\n") { (ms, text) ->
                "[${formatLrcMs(ms)}]$text"
            }
        }

        private fun parseVttOrSrtCues(raw: String): List<Pair<Long, String>> {
            val lines = raw.lines()
            val out = mutableListOf<Pair<Long, String>>()
            var idx = 0
            while (idx < lines.size) {
                val match = VTT_CUE_TIME_REGEX.find(lines[idx])
                if (match == null) {
                    idx++
                    continue
                }
                val startMs = parseTimestampMs(match.groupValues[1])
                idx++
                val textLines = mutableListOf<String>()
                while (idx < lines.size && lines[idx].isNotBlank() && !VTT_CUE_TIME_REGEX.containsMatchIn(lines[idx])) {
                    textLines += lines[idx]
                    idx++
                }
                if (startMs != null) {
                    val cleaned = cleanCueText(textLines.joinToString(" "))
                    if (cleaned != null) out += startMs to cleaned
                }
            }
            return out
        }

        private fun parseTimestampMs(raw: String): Long? {
            val normalized = raw.trim().replace(',', '.')
            val parts = normalized.split(':')
            return when (parts.size) {
                3 -> {
                    val h = parts[0].toLongOrNull() ?: return null
                    val m = parts[1].toLongOrNull() ?: return null
                    val s = parts[2].toDoubleOrNull() ?: return null
                    ((h * 3600 + m * 60) * 1000L) + (s * 1000.0).toLong()
                }
                2 -> {
                    val m = parts[0].toLongOrNull() ?: return null
                    val s = parts[1].toDoubleOrNull() ?: return null
                    (m * 60_000L) + (s * 1000.0).toLong()
                }
                else -> null
            }
        }

        private fun cleanCueText(raw: String): String? {
            val stripped = HTML_TAG_REGEX.replace(raw, " ")
                .replace("&amp;", "&")
                .replace("&lt;", "<")
                .replace("&gt;", ">")
                .replace("&quot;", "\"")
                .replace("&#39;", "'")
                .replace("&apos;", "'")
                .replace("&nbsp;", " ")
                .replace(Regex("\\s+"), " ")
                .trim()
            if (stripped.isBlank() || NOISE_CUE_REGEX.matches(stripped)) return null
            return stripped
        }

        private fun formatLrcMs(ms: Long): String {
            val clamped = ms.coerceAtLeast(0L)
            val totalSeconds = clamped / 1000L
            return String.format(
                Locale.ROOT,
                "%02d:%02d.%02d",
                totalSeconds / 60L,
                totalSeconds % 60L,
                (clamped % 1000L) / 10L
            )
        }
    }
}
